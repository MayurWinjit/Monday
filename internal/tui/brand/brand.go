package brand

import "strings"

const ASCII = `
 /$$      /$$                           /$$                    
| $$$    /$$$                          | $$                    
| $$$$  /$$$$  /$$$$$$  /$$$$$$$   /$$$$$$$  /$$$$$$  /$$   /$$
| $$ $$/$$ $$ /$$__  $$| $$__  $$ /$$__  $$ |____  $$| $$  | $$
| $$  $$$| $$| $$  \ $$| $$  \ $$| $$  | $$  /$$$$$$$| $$  | $$
| $$\  $ | $$| $$  | $$| $$  | $$| $$  | $$ /$$__  $$| $$  | $$
| $$ \/  | $$|  $$$$$$/| $$  | $$|  $$$$$$$|  $$$$$$$|  $$$$$$$
|__/     |__/ \______/ |__/  |__/ \_______/ \_______/ \____  $$
                                                      /$$  | $$
                                                     |  $$$$$$/
                                                      \______/ 
`

func Lines() []string {
	return strings.Split(strings.Trim(ASCII, "\n"), "\n")
}

func Width() int {
	w := 0
	for _, l := range Lines() {
		if len(l) > w {
			w = len(l)
		}
	}
	return w
}
